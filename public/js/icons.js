export function renderIcon(name, size = 16) {
  const icon = ICONS[name];
  if (!icon) return null;
  const rects = [];
  icon.grid.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === '.') continue;
      const fill = icon.palette[Number(c)];
      if (fill) rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`);
    }
  });
  return `<svg viewBox="0 0 12 12" width="${size}" height="${size}" shape-rendering="crispEdges" aria-label="${name}">${rects.join('')}</svg>`;
}
